async function runUpdate() {
  console.log(`Starting update for ${today}...`);
  for (const item of updates) {
    const { data, error } = await supabase
      .from('news_trends_articles')
      .update({ excerpt: item.excerpt })
      .eq('target_date', today)
      .eq('title', item.title);
    
    if (error) {
      console.error(`Error updating "${item.title}":`, error);
    } else {
      console.log(`Successfully updated: ${item.title.substring(0, 30)}...`);
    }
  }
  console.log('Update complete!');
}

runUpdate();
